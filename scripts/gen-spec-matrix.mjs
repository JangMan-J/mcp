#!/usr/bin/env node
/**
 * Generates SPEC.md: the traceability matrix of in-code requirement IDs
 * (WIRE-*, OPS-*, HTTP-*, STDIO-*, ...) to source locations and test citations.
 *
 * Policy (ratchet, both directions):
 *  - every requirement ID in scanned sources must be cited by at least one test
 *    file OR be listed in CITATION_EXEMPT below;
 *  - an exempt ID that gains a test citation must leave the exempt list.
 *
 * `--check` regenerates and fails when SPEC.md is stale or the policy breaks.
 * Default mode rewrites SPEC.md.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "SPEC.md");
const CHECK = process.argv.includes("--check");

/** Grandfathered 2026-11-25: cited nowhere under test dirs. Remove entries as tests cite them. */
const CITATION_EXEMPT = new Set([
  "AUTH-HTTP-1", "EDGE-33", "HTTP-NOGET-1", "HTTP-PARAM-2", "HTTP-PARAM-4", "HTTP-REQ-2",
  "HTTP-SSE-1", "HTTP-SSE-3", "HTTP-SSE-4", "HTTP-SSE-5", "OPS-RES-4", "OPS-TOOLS-11",
  "PAGE-4", "PROG-4", "SEC-ICON-1", "SEC-ICON-5", "STDIO-BATCH-1", "STDIO-CANCEL-1",
  "STDIO-FRAME-1", "STDIO-FRAME-2", "STDIO-LAUNCH-1", "STDIO-LIMIT-1", "STDIO-RECOVER-1",
  "STDIO-ROUTE-1", "STDIO-ROUTE-2", "STDIO-STDERR-1", "STDIO-STDERR-2", "STDIO-STDIN-1",
  "STDIO-WRITE-1", "VER-3", "WIRE-ERR-4", "WIRE-META-3",
]);

/** ID prefixes that are prose references, not requirement IDs. */
const NON_REQUIREMENT = /^(RFC|SEP|SHA|UTF|BCP|HTTP2)-/;

const ID_RE = /\b([A-Z]{2,8}(?:-[A-Z]+)*-\d+)\b/g;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) {
      if (entry === "schema") continue; // generated from pinned schema.json
      walk(p, out);
    } else if (entry.endsWith(".ts")) out.push(p);
  }
  return out;
}

function collect(files, withExcerpt) {
  const map = new Map(); // id -> [{file, line, excerpt?}]
  for (const file of files) {
    const rel = relative(ROOT, file);
    const lines = readFileSync(file, "utf8").split("\n");
    lines.forEach((raw, i) => {
      const ids = [...raw.matchAll(ID_RE)].map((m) => m[1]).filter((id) => !NON_REQUIREMENT.test(id));
      if (ids.length === 0) return;
      let excerpt = "";
      if (withExcerpt) {
        excerpt = raw.replace(/^\s*(?:\/\*\*?|\*\/?|\*)\s?/, "").replace(/\*\/\s*$/, "").trim();
        if (excerpt.length > 160) excerpt = `${excerpt.slice(0, 157)}…`;
      }
      for (const id of ids) {
        const list = map.get(id) ?? [];
        list.push(withExcerpt ? { file: rel, line: i + 1, excerpt } : { file: rel, line: i + 1 });
        map.set(id, list);
      }
    });
  }
  return map;
}

const srcFiles = [
  ...walk(join(ROOT, "packages")).filter((f) => f.includes(`${join("packages", "")}`) && f.includes("/src/")),
  ...walk(join(ROOT, "extensions")).filter((f) => !f.includes("/test/")),
];
const testFiles = [
  ...walk(join(ROOT, "packages")).filter((f) => f.includes("/test/")),
  ...walk(join(ROOT, "extensions", "test")),
];

const src = collect(srcFiles, true);
const tests = collect(testFiles, false);

const testFilesOf = (id) => [...new Set((tests.get(id) ?? []).map((r) => r.file))].sort();

const ids = [...src.keys()].sort();
const uncited = ids.filter((id) => testFilesOf(id).length === 0);
const exemptViolations = uncited.filter((id) => !CITATION_EXEMPT.has(id));
const staleExemptions = [...CITATION_EXEMPT].filter((id) => testFilesOf(id).length > 0 || !src.has(id));

// Group by package (first two path segments).
const byPackage = new Map();
for (const id of ids) {
  const first = src.get(id)[0].file;
  const pkg = first.split("/").slice(0, 2).join("/");
  if (!byPackage.has(pkg)) byPackage.set(pkg, []);
  byPackage.get(pkg).push(id);
}

let md = `# Specification Traceability Matrix

> GENERATED by \`node scripts/gen-spec-matrix.mjs\` — do not edit by hand.
> CI (\`--check\`) fails when this file is stale or when a source requirement ID
> is cited by no test and is not on the exemption list in the generator.

Requirement IDs (e.g. \`WIRE-CANCEL-1\`) appear in source comments where a
normative spec behavior is implemented, and in tests that pin it. An ID cited by
no test is either on the explicit exemption list (technical debt) or a CI failure.

- Source requirement IDs: **${ids.length}**
- Cited by at least one test: **${ids.length - uncited.length}**
- Exempt (uncited, grandfathered): **${uncited.length}**

`;

for (const [pkg, pkgIds] of [...byPackage.entries()].sort()) {
  md += `## ${pkg}\n\n| ID | Requirement (excerpt) | Source | Tests |\n|---|---|---|---|\n`;
  for (const id of pkgIds) {
    const occurrences = src.get(id);
    const excerpt = occurrences[0].excerpt.replace(/\|/g, "\\|");
    const locs = occurrences.map((o) => `\`${o.file}:${o.line}\``).join(" ");
    const cited = testFilesOf(id);
    const testCell = cited.length > 0 ? cited.map((f) => `\`${f}\``).join(" ") : (CITATION_EXEMPT.has(id) ? "— (exempt)" : "**— (uncited)**");
    md += `| ${id} | ${excerpt} | ${locs} | ${testCell} |\n`;
  }
  md += "\n";
}

md += `## Test-only IDs\n\nIDs cited in tests but not present in scanned sources (test-case IDs such as EDGE-*):\n\n`;
const testOnly = [...tests.keys()].filter((id) => !src.has(id)).sort();
md += testOnly.map((id) => `\`${id}\``).join(" ") + "\n";

const problems = [];
if (exemptViolations.length > 0) {
  problems.push(`uncited source IDs not on the exemption list: ${exemptViolations.join(", ")}`);
}
if (staleExemptions.length > 0) {
  problems.push(`exemption list entries now cited or gone (remove them): ${staleExemptions.join(", ")}`);
}

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== md) problems.push("SPEC.md is stale; run `node scripts/gen-spec-matrix.mjs`");
  if (problems.length > 0) {
    for (const p of problems) console.error(`gen-spec-matrix: ${p}`);
    process.exit(1);
  }
  console.log(`gen-spec-matrix: ok (${ids.length} source IDs, ${ids.length - uncited.length} test-cited)`);
} else {
  writeFileSync(OUT, md);
  console.log(`gen-spec-matrix: wrote SPEC.md (${ids.length} source IDs, ${ids.length - uncited.length} test-cited, ${uncited.length} exempt)`);
  for (const p of problems) console.warn(`gen-spec-matrix: warning: ${p}`);
}
